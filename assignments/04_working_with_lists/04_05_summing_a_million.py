# Creates a list of numbers from 1 to 1,000,000 and then prints the minimum, maximum, and sum of the numbers in the list.
numbers = list(range(1, 1000001))
minimum = min(numbers)
print(minimum)
maximum = max(numbers)
print(maximum)
sum = sum(numbers)
print(sum)