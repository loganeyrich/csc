# A starting list from the chapter containing 9 items
foods = ['pizza', 'pasta', 'tacos', 'burgers', 'ice cream', 'chicken', 'steak', 'fruit', 'vegetables']

# Print the first three items using a slice
print("The first three items in the list are:")
print(foods[:3])

# Print three items from the middle of the list using a slice
print("\nThree items from the middle of the list are:")
print(foods[3:6])

# Print the last three items using a negative slice
print("\nThe last three items in the list are:")
print(foods[-3:])