# If block, assigns green to the variable so the if condition is true and the player earns 5 points
alien_color = 'green'
if(alien_color == 'green'):
    print("You have gained 5 points")
else:
    print("You have gained 10 points")

# Else block, assigns yellow to the variable and because the if condition is false it prints from the 'else' statement that the player has earned 10 points
alien_color = 'yellow'
if(alien_color == 'green'):
    print("You have gained 5 points")
else:
    print("You have gained 10 points")
